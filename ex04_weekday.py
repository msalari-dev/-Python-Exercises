n = int(input("Enter your number[1-7]: "))

if n == 1:
    print("Saturday")
elif n == 2:
    print("Sunday")
elif n == 3:
    print("Monday")
elif n == 4:
    print("Tuesday")
elif n == 5:
    print("Wednesday")
elif n == 6:
    print("Thursday")
elif n == 7:
    print("Friday")
else:
    print("Invalid number!")
